type position = Lexing.position
type range = position * position
type entrypoint = (string list, location) Lexgen.automata_entry
type automata = Lex.Lexgen.automata array
type lexer = entrypoint list * automata
type token_data = { text : string; action : int }
type token = token_data Range.Located.t

let debug = false
let log s = Utils.log_src ~debug "tokenizer" s

(** Parses [source_name] into a list of entrypoints and the corresponding
    automaton. The output automata array is indexed by the states and is shared
    between entrypoints. The first component of the type parameter of
    [Lexgen.automata_entry] represents captured variables, the second one the
    range of the action snippet including braces. *)
let parse_dfa source_name =
  In_channel.with_open_bin source_name (fun ic ->
      let lexbuf = Lexing.from_channel ic in
      lexbuf.Lexing.lex_curr_p <-
        {
          Lexing.pos_fname = source_name;
          Lexing.pos_lnum = 1;
          Lexing.pos_bol = 0;
          Lexing.pos_cnum = 0;
        };
      try
        let def = Parser.lexer_definition Lexer.main lexbuf in
        let entries, automata = Lexgen.make_dfa def.entrypoints in
        Ok (entries, automata)
      with exn ->
        let bt = Printexc.get_raw_backtrace () in
        let msg =
          match exn with
          | Cset.Bad ->
              let p = Lexing.lexeme_start_p lexbuf in
              spr
                "File \"%s\", line %d, character %d: character set expected.\n"
                p.Lexing.pos_fname p.Lexing.pos_lnum
                (p.Lexing.pos_cnum - p.Lexing.pos_bol)
          | Parsing.Parse_error ->
              let p = Lexing.lexeme_start_p lexbuf in
              spr "File \"%s\", line %d, character %d: syntax error.\n"
                p.Lexing.pos_fname p.Lexing.pos_lnum
                (p.Lexing.pos_cnum - p.Lexing.pos_bol)
          | Lexer.Lexical_error (msg, file, line, col) ->
              spr "File \"%s\", line %d, character %d: %s.\n" file line col msg
          | Lexgen.Memory_overflow ->
              spr "File \"%s\":\n Position memory overflow, too many bindings\n"
                source_name
          | Output.Table_overflow ->
              spr
                "File \"%s\":\n\
                 transition table overflow, automaton is too big\n"
                source_name
          | _ -> Printexc.raise_with_backtrace exn bt
        in
        Error msg)

let stats source_file =
  let dfa = parse_dfa source_file in
  let _, arr = R.get_exn dfa in
  Array.iteri
    (fun i m ->
      match arr.(0) with
      | Lexgen.Shift (_, moves) ->
          pr "%d: %d moves\n" i (Array.length moves)
          (* 257: 2^8 chars + 1 (eof) *)
      | _ -> ())
    arr

module Token = struct
  type t = token

  let make (lexbuf : Lexing.lexbuf) action : t =
    let text =
      if lexbuf.lex_eof_reached then "eof"
      else Lexing.sub_lexeme lexbuf lexbuf.lex_start_pos lexbuf.lex_curr_pos
    in
    let startp = Lexing.lexeme_start_p lexbuf in
    if String.contains text '\n' then Lexing.new_line lexbuf;
    let endp = Lexing.lexeme_end_p lexbuf in
    Range.locate { text; action } (Range.of_lexical_positions (startp, endp))

  let yojson_of_t ({ v = { text; action }; p } : t) : Yojson.Safe.t =
    let range = Range.yojson_of_t p in
    `Assoc [ ("range", range); ("text", `String text); ("action", `Int action) ]
end

let eof = 0x100
let newline = 0xa

exception EmptyToken

(*******************************************************************************
 * Emulating what code generated by ocamllex does.
 *)

let rec __ocaml_lex_refill_buf lexbuf _buf _len _curr _last =
  if lexbuf.Lexing.lex_eof_reached then (256, _buf, _len, _curr, _last)
  else begin
    lexbuf.Lexing.lex_curr_pos <- _curr;
    lexbuf.Lexing.lex_last_pos <- _last;
    lexbuf.Lexing.refill_buff lexbuf;
    let _curr = lexbuf.Lexing.lex_curr_pos in
    let _last = lexbuf.Lexing.lex_last_pos in
    let _len = lexbuf.Lexing.lex_buffer_len in
    let _buf = lexbuf.Lexing.lex_buffer in
    if _curr < _len then
      (Char.code (Bytes.unsafe_get _buf _curr), _buf, _len, _curr + 1, _last)
    else __ocaml_lex_refill_buf lexbuf _buf _len _curr _last
  end

(** Inner loop: parses a single token and moves between states *)
let rec token automata lexbuf _buf _len _curr _last (state, last_action) =
  match automata.(state) with
  | Lexgen.Perform (action, _) ->
      log "perform %d" action;
      (* lib/outputbis.ml:205 *)
      lexbuf.Lexing.lex_curr_pos <- _curr;
      lexbuf.Lexing.lex_last_pos <- _last;
      (state, action)
  | Lexgen.Shift (rem, trans) -> (
      let _last, last_action =
        match rem with
        | Lexgen.No_remember -> (_last, last_action)
        | Lexgen.Remember (action, _) -> (_curr, action)
      in
      let next_char, _buf, _len, _curr, _last =
        if _curr >= _len then
          __ocaml_lex_refill_buf lexbuf _buf _len _curr _last
        else
          (Char.code (Bytes.unsafe_get _buf _curr), _buf, _len, _curr + 1, _last)
      in

      (* if next_char = newline then Lexing.new_line lexbuf; *)
      log "shift '%s' %d"
        (if next_char = eof then "eof" else Char.(escaped (chr next_char)))
        last_action;
      match fst trans.(next_char) with
      | Lexgen.Backtrack ->
          log "backtrack";
          (* lib/outputbis.ml:124 *)
          let _curr = _last in
          lexbuf.Lexing.lex_curr_pos <- _curr;
          lexbuf.Lexing.lex_last_pos <- _last;
          (state, last_action)
      | Lexgen.Goto state' ->
          log "%d --> %d" state state';
          token automata lexbuf _buf _len _curr _last (state', last_action))

(** Performs a single run of the rule [entrypoint], producing a token. If the
    token's [action] field is [-1], the lexer failed. *)
let next_token (lexbuf : Lexing.lexbuf) (entrypoint : entrypoint)
    (automata : Lexgen.automata array) =
  let initial = fst entrypoint.auto_initial_state in

  (* Update [lexbuf.lex_start_pos] and set the initial context of the inner loop *)
  let _curr = lexbuf.Lexing.lex_curr_pos in
  let _last = _curr in
  let _len = lexbuf.Lexing.lex_buffer_len in
  let _buf = lexbuf.Lexing.lex_buffer in
  let _last_action = -1 in
  lexbuf.Lexing.lex_start_pos <- _curr;
  log "%B eof reached" lexbuf.lex_eof_reached;

  (* Run the inner loop *)
  let state, action =
    token automata lexbuf _buf _len _curr _last (initial, _last_action)
  in

  (* Update the position fields of lexbuf with the new offsets *)
  begin
    let _curr_p = lexbuf.Lexing.lex_curr_p in
    if _curr_p != Lexing.dummy_pos then begin
      lexbuf.Lexing.lex_start_p <- _curr_p;
      lexbuf.Lexing.lex_curr_p <-
        {
          _curr_p with
          Lexing.pos_cnum =
            lexbuf.Lexing.lex_abs_pos + lexbuf.Lexing.lex_curr_pos;
        }
    end
  end;

  Token.make lexbuf action

(** Outer loop: parses tokens through multiple runs of the same rule
    [entrypoint], collects into a list. *)
let rec tokenize (lexbuf : Lexing.lexbuf) (entrypoint : entrypoint)
    (automata : Lexgen.automata array) (tokens : Token.t list) =
  let tok = next_token lexbuf entrypoint automata in
  let tokens = tok :: tokens in

  if tok.v.action < 0 then (
    (* Exception: empty token. We are interested in this event so we still produce a token (with empty text and action of -1) which we treat specially in the UI. *)
    log "empty token found";
    List.rev tokens)
  else if lexbuf.lex_eof_reached then (
    log "%B eof reached" lexbuf.lex_eof_reached;
    List.rev tokens)
  else tokenize lexbuf entrypoint automata tokens

let tokenize_with_idx ~start_rule_idx lexbuf (entrypoints, auto) =
  tokenize lexbuf (List.nth entrypoints start_rule_idx) auto []

let tokenize_with_entry lexbuf entrypoint automata =
  tokenize lexbuf entrypoint automata []

module Persistent = struct
  type lexbuf = {
    lex_start_pos : int;
    lex_curr_pos : int;
    lex_eof_reached : bool;
    lex_start_p : position;
    lex_curr_p : position;
  }
  (** In order to support reversibility we prefer working with a persistent
      version of the lexbuf record. We also avoind chunking the content of the
      input text so we hold the whole content inside a separate buffer, in a
      similar fashion to the buffers produced by [Lexing.from_string] *)

  let zero_pos : position =
    { pos_fname = ""; pos_lnum = 1; pos_bol = 0; pos_cnum = 0 }

  let start_lexbuf : lexbuf =
    {
      lex_start_pos = 0;
      lex_curr_pos = 0;
      lex_eof_reached = false;
      lex_start_p = zero_pos;
      lex_curr_p = zero_pos;
    }

  module Token = struct
    include Token

    let make (buffer : Bytes.t) (lexbuf : lexbuf) action : t =
      let text =
        (* if lexbuf.lex_start_pos = Bytes.length buffer then "eof" *)
        if lexbuf.lex_eof_reached then "eof"
        else
          let len = lexbuf.lex_curr_pos - lexbuf.lex_start_pos in
          Bytes.sub_string buffer lexbuf.lex_start_pos len
      in
      let startp = lexbuf.lex_start_p in
      let endp = lexbuf.lex_curr_p in
      Range.locate { text; action } (Range.of_lexical_positions (startp, endp))
  end

  (** Inner loop: parses a single token and moves between states. Tail
      recursive.

      Here we emulate the behavior of code generated ocamllex in [-ml] backend,
      with a few enhancements:
      + Pure logic, no mutable fields or side effects thanks to persistent
        lexbuf data type with smaller memory footprint;
      + Newline detection and up-to-date line number and BOL field in computed
        positions. *)
  let rec token automata lexbuf _buf _len _curr _curr_p _last _last_p
      (state, last_action) =
    match automata.(state) with
    | Lexgen.Perform (action, _) ->
        log "perform %d" action;
        (* lib/outputbis.ml:205 *)
        let lexbuf =
          { lexbuf with lex_curr_pos = _curr; lex_curr_p = _curr_p }
        in
        (lexbuf, state, action)
        (* First exit *)
    | Lexgen.Shift (rem, trans) -> (
        (* Remember the last position and whether eof was reached in case the shift action triggers a backtrack.

      When the lexer shifts [eof] just before backtracking we refrain from setting the [lex_eof_reached] to allow the outer loop to do something interesting with the [eof] character. The next run of [token] will shift [eof] again, either perform an action (action <> -1) or reject it (action = -1) and turn on [lex_eof_reached] in the result; then the outer loop can exit safely. *)
        let last_eof = lexbuf.lex_eof_reached in
        let _last, _last_p, last_action =
          match rem with
          | Lexgen.No_remember -> (_last, _last_p, last_action)
          | Lexgen.Remember (action, _) ->
              log "remember %d" action;
              (_curr, _curr_p, action)
        in
        let next_char, _curr =
          if _curr >= _len then (eof, _curr)
          else (Char.code (Bytes.unsafe_get _buf _curr), _curr + 1)
        in

        let _curr_p =
          if next_char = newline then
            Lexing.
              {
                _curr_p with
                pos_cnum = _curr;
                pos_lnum = _curr_p.pos_lnum + 1;
                pos_bol = _curr;
              }
          else Lexing.{ _curr_p with pos_cnum = _curr }
        in

        let eof_reached = next_char = eof in
        let lexbuf = { lexbuf with lex_eof_reached = eof_reached } in

        log "shift '%s' %d"
          (if next_char = eof then "eof" else Char.(escaped (chr next_char)))
          last_action;
        match fst trans.(next_char) with
        | Lexgen.Backtrack ->
            log "backtrack";
            (* lib/outputbis.ml:124 *)
            let _curr = _last in
            let _curr_p = _last_p in
            let eof_reached = last_eof in
            let lexbuf =
              {
                lexbuf with
                lex_curr_pos = _curr;
                lex_curr_p = _curr_p;
                lex_eof_reached = eof_reached;
              }
            in
            (lexbuf, state, last_action)
            (* Second exit *)
        | Lexgen.Goto state' ->
            log "%d --> %d" state state';
            token automata lexbuf _buf _len _curr _curr_p _last _last_p
              (state', last_action))

  (** Performs a single run of the rule [entrypoint], producing a token. If the
      token's [action] field is [-1], the lexer failed. We refer as "outer loop"
      any function that calls [next_token] repeatedly. *)
  let next_token (buffer : Bytes.t) (lexbuf : lexbuf) (entrypoint : entrypoint)
      (automata : Lexgen.automata array) =
    let initial = fst entrypoint.auto_initial_state in

    (* Update the start positions of the lexbuf to the end positions of the last token and set the initial context of the inner loop *)
    let _curr = lexbuf.lex_curr_pos in
    let _curr_p = lexbuf.lex_curr_p in
    let _last = _curr in
    let _last_p = _curr_p in
    let _len = Bytes.length buffer in
    let _last_action = -1 in

    let lexbuf = { lexbuf with lex_start_pos = _curr; lex_start_p = _curr_p } in

    (* Run the inner loop *)
    let lexbuf, state, action =
      token automata lexbuf buffer _len _curr _curr_p _last _last_p
        (initial, _last_action)
    in

    (lexbuf, Token.make buffer lexbuf action)

  (** Outer loop: parses tokens through multiple runs of the same rule
      [entrypoint], collects into a list. *)
  let rec tokenize (buffer : Bytes.t) (lexbuf : lexbuf)
      (entrypoint : entrypoint) (automata : Lexgen.automata array)
      (tokens : Token.t list) =
    let lexbuf, tok = next_token buffer lexbuf entrypoint automata in
    let tokens = tok :: tokens in

    if tok.v.action < 0 then (
      (* Exception: empty token. We are interested in this event so we still produce a token (with empty text and action of -1) which we treat specially in the UI. *)
      log "empty token found";
      List.rev tokens)
    else if lexbuf.lex_eof_reached then (
      log "%B eof reached" lexbuf.lex_eof_reached;
      List.rev tokens)
    else tokenize buffer lexbuf entrypoint automata tokens

  let tokenize_with_idx ~start_rule_idx buffer lexbuf (entrypoints, auto) =
    tokenize buffer lexbuf (List.nth entrypoints start_rule_idx) auto []

  let tokenize_with_entry buffer lexbuf entrypoint automata =
    tokenize buffer lexbuf entrypoint automata []
end
