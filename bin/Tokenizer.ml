let debug = false
let log s = Utils.log_src ~debug "tokenizer" s

(** Parses [source_name] into a list of entrypoints and the corresponding
    automaton. The output automata array is indexed by the states and is shared
    between entrypoints. The first component of the type parameter of
    [Lexgen.automata_entry] represents captured variables, the second one the
    range of the action snippet including braces. *)
let parse_dfa source_name =
  In_channel.with_open_bin source_name (fun ic ->
      let lexbuf = Lexing.from_channel ic in
      lexbuf.Lexing.lex_curr_p <-
        {
          Lexing.pos_fname = source_name;
          Lexing.pos_lnum = 1;
          Lexing.pos_bol = 0;
          Lexing.pos_cnum = 0;
        };
      try
        let def = Parser.lexer_definition Lexer.main lexbuf in
        let entries, automata = Lexgen.make_dfa def.entrypoints in
        Ok (entries, automata)
      with exn ->
        let bt = Printexc.get_raw_backtrace () in
        let msg =
          match exn with
          | Cset.Bad ->
              let p = Lexing.lexeme_start_p lexbuf in
              spr
                "File \"%s\", line %d, character %d: character set expected.\n"
                p.Lexing.pos_fname p.Lexing.pos_lnum
                (p.Lexing.pos_cnum - p.Lexing.pos_bol)
          | Parsing.Parse_error ->
              let p = Lexing.lexeme_start_p lexbuf in
              spr "File \"%s\", line %d, character %d: syntax error.\n"
                p.Lexing.pos_fname p.Lexing.pos_lnum
                (p.Lexing.pos_cnum - p.Lexing.pos_bol)
          | Lexer.Lexical_error (msg, file, line, col) ->
              spr "File \"%s\", line %d, character %d: %s.\n" file line col msg
          | Lexgen.Memory_overflow ->
              spr "File \"%s\":\n Position memory overflow, too many bindings\n"
                source_name
          | Output.Table_overflow ->
              spr
                "File \"%s\":\n\
                 transition table overflow, automaton is too big\n"
                source_name
          | _ -> Printexc.raise_with_backtrace exn bt
        in
        Error msg)

let stats source_file =
  let dfa = parse_dfa source_file in
  let _, arr = R.get_exn dfa in
  Array.iteri
    (fun i m ->
      match arr.(0) with
      | Lexgen.Shift (_, moves) ->
          pr "%d: %d moves\n" i (Array.length moves)
          (* 257: 2^8 chars + 1 (eof) *)
      | _ -> ())
    arr

module Token = struct
  type data = { text : string; action : int }
  type t = data Range.located

  let make (lexbuf : Lexing.lexbuf) action : t =
    let text =
      if lexbuf.lex_eof_reached then "eof"
      else Lexing.sub_lexeme lexbuf lexbuf.lex_start_pos lexbuf.lex_curr_pos
    in
    let startp = Lexing.lexeme_start_p lexbuf in
    if String.contains text '\n' then Lexing.new_line lexbuf;
    let endp = Lexing.lexeme_end_p lexbuf in
    Range.locate { text; action } (Range.of_lexical_positions (startp, endp))

  let yojson_of_t ({ v = { text; action }; p } : t) : Yojson.Safe.t =
    let range = Range.yojson_of_t p in
    `Assoc [ ("range", range); ("text", `String text); ("action", `Int action) ]
end

let eof = 0x100

