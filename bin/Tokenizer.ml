(*******************************************************************************
 * Emulating what code generated by ocamllex does.
 *)

let rec __ocaml_lex_refill_buf lexbuf _buf _len _curr _last =
  if lexbuf.Lexing.lex_eof_reached then (256, _buf, _len, _curr, _last)
  else begin
    lexbuf.Lexing.lex_curr_pos <- _curr;
    lexbuf.Lexing.lex_last_pos <- _last;
    lexbuf.Lexing.refill_buff lexbuf;
    let _curr = lexbuf.Lexing.lex_curr_pos in
    let _last = lexbuf.Lexing.lex_last_pos in
    let _len = lexbuf.Lexing.lex_buffer_len in
    let _buf = lexbuf.Lexing.lex_buffer in
    if _curr < _len then
      (Char.code (Bytes.unsafe_get _buf _curr), _buf, _len, _curr + 1, _last)
    else __ocaml_lex_refill_buf lexbuf _buf _len _curr _last
  end

(** Inner loop: parses a single token and moves between states *)
let rec token automata lexbuf _buf _len _curr _last (state, last_action) =
  match automata.(state) with
  | Lexgen.Perform (action, _) ->
      log "perform %d" action;
      (* lib/outputbis.ml:205 *)
      lexbuf.Lexing.lex_curr_pos <- _curr;
      lexbuf.Lexing.lex_last_pos <- _last;
      (state, action)
  | Lexgen.Shift (rem, trans) -> (
      let _last, last_action =
        match rem with
        | Lexgen.No_remember -> (_last, last_action)
        | Lexgen.Remember (action, _) -> (_curr, action)
      in
      let next_char, _buf, _len, _curr, _last =
        if _curr >= _len then
          __ocaml_lex_refill_buf lexbuf _buf _len _curr _last
        else
          (Char.code (Bytes.unsafe_get _buf _curr), _buf, _len, _curr + 1, _last)
      in
      log "shift '%s' %d"
        (if next_char = eof then "eof" else Char.(escaped (chr next_char)))
        last_action;
      if next_char = Char.code '\n' then Lexing.new_line lexbuf;
      match fst trans.(next_char) with
      | Lexgen.Backtrack ->
          log "backtrack";
          (* lib/outputbis.ml:124 *)
          let _curr = _last in
          lexbuf.Lexing.lex_curr_pos <- _curr;
          lexbuf.Lexing.lex_last_pos <- _last;
          (state, last_action)
      | Lexgen.Goto state' ->
          log "%d --> %d" state state';
          token automata lexbuf _buf _len _curr _last (state', last_action))

(** Outer loop: parses tokens, analyses actions and moves between entrypoints *)
let rec tokenize (lexbuf : Lexing.lexbuf) (entrypoint : entrypoint)
    (automata : Lexgen.automata array) (tokens : Token.t list) =
  let initial = fst entrypoint.auto_initial_state in

  let _curr = lexbuf.Lexing.lex_curr_pos in
  let _last = _curr in
  let _len = lexbuf.Lexing.lex_buffer_len in
  let _buf = lexbuf.Lexing.lex_buffer in
  let _last_action = -1 in
  lexbuf.Lexing.lex_start_pos <- _curr;

  log "%B eof reached" lexbuf.lex_eof_reached;
  let state, action =
    token automata lexbuf _buf _len _curr _last (initial, _last_action)
  in

  begin
    let _curr_p = lexbuf.Lexing.lex_curr_p in
    if _curr_p != Lexing.dummy_pos then begin
      lexbuf.Lexing.lex_start_p <- _curr_p;
      lexbuf.Lexing.lex_curr_p <-
        {
          _curr_p with
          Lexing.pos_cnum =
            lexbuf.Lexing.lex_abs_pos + lexbuf.Lexing.lex_curr_pos;
        }
    end
  end;

  if action < 0 then List.rev tokens
  else
    let tokens = Token.make lexbuf :: tokens in
    (* Don't use lexbuf.lex_eof_reached, it's always true *)
    if lexbuf.lex_eof_reached then (
      log "%B eof reached" lexbuf.lex_eof_reached;
      List.rev tokens)
    else tokenize lexbuf entrypoint automata tokens

let tokenize ~start_rule_idx lexbuf (entrypoints, auto) =
  tokenize lexbuf (List.nth entrypoints start_rule_idx) auto []

let tokenize_to_json i l a : Yojson.Safe.t =
  let res = tokenize ~start_rule_idx:i l a in
  `List (L.map Token.yojson_of_t res)
